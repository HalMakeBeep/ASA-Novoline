#include <cstdio>
#include <cstdlib>
#include <vector>

static const unsigned char XOR_KEY[32] = {
    0xA7, 0x3B, 0xF2, 0x19, 0xD4, 0x8E, 0x61, 0xC5,
    0x0D, 0x72, 0xAA, 0x4F, 0xE8, 0x36, 0x9C, 0x5B,
    0x14, 0xDF, 0x83, 0x27, 0x6A, 0xB1, 0xF5, 0x48,
    0x90, 0x0E, 0xCC, 0x7D, 0x53, 0xA2, 0x3F, 0x66,
};

int main(int argc, char* argv[]) {
    if (argc != 3) {
        fprintf(stderr, "Usage: embed_dll <input.dll> <output.h>\n");
        return 1;
    }

    // Read DLL
    FILE* in = fopen(argv[1], "rb");
    if (!in) {
        fprintf(stderr, "Cannot open %s\n", argv[1]);
        return 1;
    }
    fseek(in, 0, SEEK_END);
    long size = ftell(in);
    fseek(in, 0, SEEK_SET);

    std::vector<unsigned char> data(size);
    fread(data.data(), 1, size, in);
    fclose(in);

    // XOR encrypt
    for (long i = 0; i < size; i++)
        data[i] ^= XOR_KEY[i % 32];

    // Write header
    FILE* out = fopen(argv[2], "w");
    if (!out) {
        fprintf(stderr, "Cannot write %s\n", argv[2]);
        return 1;
    }

    fprintf(out, "#pragma once\n");
    fprintf(out, "// Auto-generated by embed_dll — DO NOT EDIT\n\n");
    fprintf(out, "#include <cstddef>\n\n");

    fprintf(out, "constexpr unsigned char EMBEDDED_DLL_KEY[32] = {\n");
    for (int i = 0; i < 32; i += 16) {
        fprintf(out, "    ");
        for (int j = i; j < i + 16 && j < 32; j++)
            fprintf(out, "0x%02X%s", XOR_KEY[j], j < 31 ? ", " : "");
        fprintf(out, "\n");
    }
    fprintf(out, "};\n\n");

    fprintf(out, "constexpr size_t EMBEDDED_DLL_SIZE = %ld;\n\n", size);

    fprintf(out, "constexpr unsigned char EMBEDDED_DLL_DATA[] = {\n");
    for (long i = 0; i < size; i += 16) {
        fprintf(out, "    ");
        for (long j = i; j < i + 16 && j < size; j++)
            fprintf(out, "0x%02X, ", data[j]);
        fprintf(out, "\n");
    }
    fprintf(out, "};\n");

    fclose(out);
    printf("Embedded %ld bytes (%.1f MB) -> %s\n", size, size / (1024.0 * 1024.0), argv[2]);
    return 0;
}
